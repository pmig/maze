//! Embeds the update signing public keys (`keys/update_public_keys.txt`, or the
//! `MAZEMAIL_UPDATE_PUBLIC_KEYS` environment variable) as `$OUT_DIR/public_keys.rs`.

#![allow(
    clippy::print_stdout,
    reason = "build scripts talk to Cargo through stdout"
)]

use std::path::PathBuf;
use std::{env, fs};

use base64::Engine as _;
use base64::engine::general_purpose::STANDARD;

const KEYS_ENV: &str = "MAZEMAIL_UPDATE_PUBLIC_KEYS";
const MAX_KEYS: usize = 2;
/// Test-only override of `RELEASE_CHANNEL` (see `release_channel`'s build script).
const CHANNEL_OVERRIDE_ENV: &str = "MAZEMAIL_BUILD_CHANNEL";

fn main() {
    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap_or_else(|| ".".into()));
    let keys_file = manifest_dir.join("keys/update_public_keys.txt");
    let channel_file = manifest_dir.join("../mazemail/RELEASE_CHANNEL");
    println!("cargo::rerun-if-changed={}", keys_file.display());
    println!("cargo::rerun-if-changed={}", channel_file.display());
    println!("cargo::rerun-if-env-changed={KEYS_ENV}");
    println!("cargo::rerun-if-env-changed={CHANNEL_OVERRIDE_ENV}");

    let (source, text) = match env::var(KEYS_ENV) {
        Ok(value) if !value.trim().is_empty() => (KEYS_ENV.to_owned(), value),
        _ => (
            keys_file.display().to_string(),
            fs::read_to_string(&keys_file)
                .unwrap_or_else(|err| panic!("cannot read {}: {err}", keys_file.display())),
        ),
    };

    let keys: Vec<[u8; 32]> = text
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .flat_map(|line| line.split([',', ' ', '\t']))
        .filter(|key| !key.is_empty())
        .map(|key| {
            let bytes = STANDARD
                .decode(key)
                .unwrap_or_else(|err| panic!("{source}: {key:?} is not base64: {err}"));
            <[u8; 32]>::try_from(bytes.as_slice())
                .unwrap_or_else(|_| panic!("{source}: {key:?} is not 32 bytes"))
        })
        .collect();
    assert!(
        keys.len() <= MAX_KEYS,
        "{source}: at most {MAX_KEYS} update keys are supported, found {}",
        keys.len()
    );

    let channel = env::var(CHANNEL_OVERRIDE_ENV)
        .ok()
        .filter(|channel| !channel.trim().is_empty())
        .unwrap_or_else(|| fs::read_to_string(&channel_file).unwrap_or_default());
    if keys.is_empty() && matches!(channel.trim(), "preview" | "stable") {
        println!(
            "cargo::warning=no update public keys embedded ({source}); this {} build will not update itself",
            channel.trim()
        );
    }

    let mut out = String::from(
        "/// Ed25519 public keys trusted to sign update manifests (generated by build.rs).\n\
         pub(crate) const EMBEDDED_PUBLIC_KEYS: &[[u8; 32]] = &[\n",
    );
    for key in &keys {
        out.push_str(&format!("    {key:?},\n"));
    }
    out.push_str("];\n");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap_or_else(|| ".".into()));
    fs::write(out_dir.join("public_keys.rs"), out)
        .unwrap_or_else(|err| panic!("cannot write public_keys.rs: {err}"));
}
